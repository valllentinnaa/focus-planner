-- Wishlist — your own list of things you'd like, shareable by a private link.
--
-- wishlist_items   owner-only (RLS), like every other table.
-- wishlist_shares  one private link per user; the token is 128 random bits. Turning the link off
--                  deletes the row, so an old link stops working for good.
-- wishlist_claims  "I'm getting this" marks from people with the link. Nobody can read this table
--                  directly — not even the owner, so the surprise holds. Visitors see only a
--                  claimed yes/no through get_shared_wishlist().
-- Visitors (signed in or not) reach the list ONLY through the three functions below.

create table public.wishlist_items (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  text text not null check (char_length(text) between 1 and 500),
  link text check (link is null or (char_length(link) <= 2000 and link ~* '^https?://')),
  note text not null default '' check (char_length(note) <= 500),
  position integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index wishlist_items_user on public.wishlist_items (user_id, position);
create trigger wishlist_items_updated_at before update on public.wishlist_items
  for each row execute function public.set_updated_at();

create table public.wishlist_shares (
  user_id uuid primary key default auth.uid() references auth.users (id) on delete cascade,
  token text not null unique default encode(extensions.gen_random_bytes(16), 'hex') check (token ~ '^[0-9a-f]{32}$'),
  created_at timestamptz not null default now()
);

create table public.wishlist_claims (
  item_id uuid primary key references public.wishlist_items (id) on delete cascade,
  -- sha256 of a random key kept by the claimer's browser, so only they can undo it.
  claim_key_hash text not null,
  created_at timestamptz not null default now()
);

do $$
declare t text;
begin
  foreach t in array array['wishlist_items','wishlist_shares']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('alter table public.%I force row level security', t);
    execute format('create policy "%1$s owner select" on public.%1$I for select to authenticated using (user_id = auth.uid())', t);
    execute format('create policy "%1$s owner insert" on public.%1$I for insert to authenticated with check (user_id = auth.uid())', t);
    execute format('create policy "%1$s owner delete" on public.%1$I for delete to authenticated using (user_id = auth.uid())', t);
    execute format('revoke all on public.%I from anon', t);
  end loop;
end $$;
create policy "wishlist_items owner update" on public.wishlist_items for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());
-- The token is generated by the database, never chosen by the client.
revoke insert, update on public.wishlist_shares from authenticated;
grant insert (user_id) on public.wishlist_shares to authenticated;

alter table public.wishlist_claims enable row level security;
alter table public.wishlist_claims force row level security;
revoke all on public.wishlist_claims from anon, authenticated;

-- ---------- functions for people with the link ----------
create or replace function public.get_shared_wishlist(p_token text)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare owner uuid;
begin
  if p_token is null or p_token !~ '^[0-9a-f]{32}$' then return null; end if;
  select user_id into owner from wishlist_shares where token = p_token;
  if owner is null then return null; end if;
  return jsonb_build_object(
    'owner', (select display_name from profiles where id = owner),
    -- The owner opening their own link never sees who claimed what.
    'is_owner', owner = auth.uid(),
    'items', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', i.id, 'text', i.text, 'link', i.link, 'note', i.note,
               'claimed', owner is distinct from auth.uid() and exists (select 1 from wishlist_claims c where c.item_id = i.id))
             order by i.position, i.created_at)
      from wishlist_items i where i.user_id = owner), '[]'::jsonb)
  );
end $$;

create or replace function public.claim_wishlist_item(p_token text, p_item uuid, p_key text)
returns boolean language plpgsql volatile security definer set search_path = public as $$
declare owner uuid;
begin
  if p_token !~ '^[0-9a-f]{32}$' or char_length(coalesce(p_key, '')) not between 32 and 128 then return false; end if;
  select user_id into owner from wishlist_shares where token = p_token;
  if owner is null or owner = auth.uid() then return false; end if;
  if not exists (select 1 from wishlist_items where id = p_item and user_id = owner) then return false; end if;
  insert into wishlist_claims (item_id, claim_key_hash)
    values (p_item, encode(extensions.digest(p_key, 'sha256'), 'hex'))
    on conflict (item_id) do nothing;
  return found;
end $$;

create or replace function public.unclaim_wishlist_item(p_token text, p_item uuid, p_key text)
returns boolean language plpgsql volatile security definer set search_path = public as $$
declare owner uuid;
begin
  if p_token !~ '^[0-9a-f]{32}$' or p_key is null then return false; end if;
  select user_id into owner from wishlist_shares where token = p_token;
  if owner is null then return false; end if;
  delete from wishlist_claims c using wishlist_items i
    where c.item_id = p_item and i.id = c.item_id and i.user_id = owner
      and c.claim_key_hash = encode(extensions.digest(p_key, 'sha256'), 'hex');
  return found;
end $$;

revoke all on function public.get_shared_wishlist(text) from public;
revoke all on function public.claim_wishlist_item(text, uuid, text) from public;
revoke all on function public.unclaim_wishlist_item(text, uuid, text) from public;
grant execute on function public.get_shared_wishlist(text) to anon, authenticated;
grant execute on function public.claim_wishlist_item(text, uuid, text) to anon, authenticated;
grant execute on function public.unclaim_wishlist_item(text, uuid, text) to anon, authenticated;
